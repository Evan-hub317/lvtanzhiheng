# ============ 电网区域因子（生态环境部 2022 年度公告，kgCO2/kWh → tCO2/万kWh） ============
GRID_FACTORS = [("HB", "华北区域电网", 9.81), ("DB", "东北区域电网", 10.603),
                ("HD", "华东区域电网", 7.496), ("HZ", "华中区域电网", 6.231),
                ("XB", "西北区域电网", 7.094), ("NF", "南方区域电网", 5.217)]


def city_weight(code, default):
    """确定性权重抖动 ±12%，保证可重复"""
    h = int(hashlib.md5(code.encode()).hexdigest()[:8], 16)
    jitter = 1.0 + (h % 24 - 12) / 100.0
    return default * jitter


def build_sql():
    lines = []
    lines.append("-- =================================================================")
    lines.append("-- 全国行政区划 + 省级参数 + 区域电网因子 种子数据")
    lines.append("-- 生成：tools/gen_regions.py   数据口径：GB/T 2260（民政部）")
    lines.append("-- 省级 GDP/能耗等参数为国家统计局公开统计近似值（演示口径）")
    lines.append("-- 电网因子来源：生态环境部 2022 年度全国电网平均排放因子公告")
    lines.append("-- 幂等：region_code 唯一键 + INSERT IGNORE，可重复执行")
    lines.append("-- =================================================================")
    lines.append("USE smart_carbon;")
    lines.append("")

    # 1. 省级区域
    lines.append("-- 1. 省级行政区（level=1）")
    for code, name, gdp, *_ in PROVINCES:
        lines.append(f"INSERT IGNORE INTO dim_region (region_code, region_name, parent_id, level, gdp, sort_order) "
                     f"VALUES ('{code}', '{name}', 0, 1, {gdp}, 0);")
    lines.append("")

    # 2. 市级区域（含直辖市辖区），GDP 按权重分配
    lines.append("-- 2. 市级行政区（level=2，GDP 按省 GDP 权重分配，万亿城市按公开排名加权）")
    for code, name, gdp, *_ in PROVINCES:
        entries = []
        if code in CITIES:
            for ccode, cname, weight in CITIES[code]:
                entries.append((ccode, cname, weight))
        if code in DISTRICTS:
            n = len(DISTRICTS[code])
            for ccode, cname in DISTRICTS[code]:
                entries.append((ccode, cname, 1.0))
        # 计算权重和，分配 GDP
        weights = [city_weight(ccode, w) for ccode, _, w in entries]
        total_w = sum(weights)
        for (ccode, cname, _), w in zip(entries, weights):
            city_gdp = round(gdp * w / total_w, 2)
            lines.append(f"INSERT IGNORE INTO dim_region (region_code, region_name, parent_id, level, gdp, sort_order) "
                         f"SELECT '{ccode}', '{cname}', r.id, 2, {city_gdp}, 0 FROM dim_region r WHERE r.region_code = '{code}';")
    lines.append("")

    # 3. 省级参数表
    lines.append("-- 3. 省级参数表")
    lines.append("CREATE TABLE IF NOT EXISTS province_param (")
    lines.append("  region_id       INT          NOT NULL COMMENT '省级区域ID',")
    lines.append("  gdp             DECIMAL(16,2) NOT NULL COMMENT 'GDP（亿元）',")
    lines.append("  secondary_ratio DECIMAL(8,2)  NOT NULL COMMENT '第二产业占GDP比重（%）',")
    lines.append("  coal_ratio      DECIMAL(8,2)  NOT NULL COMMENT '煤炭占能源消费比重（%）',")
    lines.append("  energy_intensity DECIMAL(8,4) NOT NULL COMMENT '单位GDP能耗（吨标煤/万元）',")
    lines.append("  grid_code       VARCHAR(10)   NOT NULL COMMENT '电网区域：HB/DB/HD/HZ/XB/NF',")
    lines.append("  heating         TINYINT       NOT NULL DEFAULT 0 COMMENT '是否供暖省份：1是 0否',")
    lines.append("  gdp_growth      DECIMAL(6,2)  NOT NULL DEFAULT 5.0 COMMENT 'GDP年均增速（%）',")
    lines.append("  PRIMARY KEY (region_id)")
    lines.append(") ENGINE=InnoDB COMMENT='省级经济能源特征参数（公开统计近似值）';")
    lines.append("")
    for code, name, gdp, sec, coal, ei, grid, heating, growth in PROVINCES:
        lines.append(f"INSERT INTO province_param (region_id, gdp, secondary_ratio, coal_ratio, energy_intensity, grid_code, heating, gdp_growth) ")
        lines.append(f"SELECT r.id, {gdp}, {sec}, {coal}, {ei}, '{grid}', {heating}, {growth} FROM dim_region r WHERE r.region_code = '{code}' ")
        lines.append("ON DUPLICATE KEY UPDATE gdp = VALUES(gdp), secondary_ratio = VALUES(secondary_ratio), coal_ratio = VALUES(coal_ratio), energy_intensity = VALUES(energy_intensity), grid_code = VALUES(grid_code), heating = VALUES(heating), gdp_growth = VALUES(gdp_growth);")
    lines.append("")

    # 4. 电网区域因子
    lines.append("-- 4. 排放因子表增加电网区域维度（幂等）")
    lines.append("SET @col_exists = (SELECT COUNT(*) FROM information_schema.columns "
                 "WHERE table_schema = DATABASE() AND table_name = 'factor_emission' AND column_name = 'grid_code');")
    lines.append("SET @sql = IF(@col_exists = 0, "
                 "\"ALTER TABLE factor_emission ADD COLUMN grid_code VARCHAR(10) DEFAULT NULL COMMENT '电网区域编码（仅电力因子使用）' AFTER energy_id\", 'SELECT 1');")
    lines.append("PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;")
    lines.append("")
    lines.append("-- 替换旧单一全国电力因子为六大区域电网因子（能源品种7=电力）")
    lines.append("DELETE FROM factor_emission WHERE energy_id = 7;")
    for grid, gname, factor in GRID_FACTORS:
        lines.append(f"INSERT IGNORE INTO factor_emission (energy_id, grid_code, factor_value, oxid_rate, data_source, effective_year, remark) "
                     f"VALUES (7, '{grid}', {factor}, 1.0000, '生态环境部2022年度全国电网平均排放因子公告', 2024, '{gname} tCO2/万千瓦时');")
    lines.append("")
    return "\n".join(lines) + "\n"


